/**
 * A differential cross check of the original `Blob_Labeler` against the MoonBit
 * port.
 *
 * The QA report listed as a residual risk that the labeling of the blobs was
 * only covered by the **image corpus** - the twenty five images of the suite -
 * and never by a fuzz. The labeling is the most intricate algorithm of the
 * port (the HIPR2 algorithm with a union-find style merge and a condensation of
 * the labels), and its interesting cases are exactly the ones a corpus does
 * not contain: many separate blobs, blobs that touch, blobs with a hole, the
 * border of the image and the two failure modes of the plugin.
 *
 * So both implementations are driven with the **same** random images and the
 * results are pinned to **shared checksums**:
 *
 *   * this tool fails when the **Java** original computes something else,
 *   * the MoonBit test fails when the **port** computes something else,
 *
 * so a divergence shows up on the side that caused it. The images are
 * generated by a linear congruential generator, so no file has to be
 * exchanged.
 *
 * The six configurations are the ones of the reference harness: the 4 and the 8
 * connected neighbourhood, with and without the edge correction, and with the
 * background colour 0 and 1.
 *
 * Every run is folded into the checksum of its configuration:
 *
 *   * the failure flag (the plugin raises an `ArrayIndexOutOfBoundsException`
 *     when it has more labels than `size/2` or when it reads a neighbour
 *     outside a one row or one column high image),
 *   * the number of labels,
 *   * every value of the label map, in row major order.
 *
 * A run that raises is reported the way the reference harness reports it: an
 * empty label map, no labels and the failure flag set.
 *
 * Usage:
 *     javac -encoding UTF-8 -cp out -d tools\out tools\BlobCrossCheck.java
 *     java -cp "out;tools\out" BlobCrossCheck [count]
 *
 * With a different number of images the checksums are only reported (the
 * constants belong to the default number of images).
 */
public class BlobCrossCheck {
    /** The number of random images. */
    public static final int COUNT = 96;

    /** The seed of the linear congruential generator. */
    public static final int SEED = 20261030;

    /** The modulus of the checksum. */
    private static final long MOD = 1000000007L;

    /** The names of the six configurations. */
    public static final String[] NAMES = {
        "blob4", "blob8", "blob4_noedge", "blob8_noedge", "blob4_bgcol", "blob8_bgcol"
    };

    /** The neighbourhood of every configuration (true is the 8 connected one). */
    public static final boolean[] EIGHT = { false, true, false, true, false, true };

    /** The background colour of every configuration. */
    public static final int[] BGCOL = { 0, 0, 0, 0, 1, 1 };

    /** The edge correction of every configuration. */
    public static final boolean[] EDGE = { true, true, false, false, true, true };

    /** The checksum of every configuration, in the order of {@link #NAMES}. */
    public static final long[] EXPECTED_CHECKSUMS = {
        717071813L, 41598674L, 99965418L, 549135478L, 470942760L, 776978089L
    };

    /** The number of failing rounds of every configuration. */
    public static final int[] EXPECTED_FAILURES = {
        6, 6, 22, 29, 6, 6
    };

    /** The widths of the images. */
    public static final int[] WIDTHS = {
        8, 12, 16, 24, 7, 32, 1, 8, 1, 2, 5, 1, 10, 20, 3, 15
    };

    /** The heights of the images. */
    public static final int[] HEIGHTS = {
        8, 10, 16, 18, 5, 24, 8, 1, 1, 3, 1, 5, 7, 20, 3, 11
    };

    /** The state of the generator. */
    private static int state = SEED;

    /** The next value of the generator (the same arithmetic as in Java). */
    private static int next() {
        state = (1103515245 * state + 12345) & 0x7FFFFFFF;
        return state;
    }

    public static void main(String[] args) throws Exception {
        int count = args.length > 0 ? Integer.parseInt(args[0]) : COUNT;
        long[] checksums = new long[NAMES.length];
        int[] failures = new int[NAMES.length];

        // the plugin reads its settings from static fields
        java.lang.reflect.Field segment = Blob_Labeler.class.getDeclaredField("segment");
        segment.setAccessible(true);
        segment.setBoolean(null, false);
        java.lang.reflect.Field neighb8 = Blob_Labeler.class.getDeclaredField("neighb8");
        neighb8.setAccessible(true);
        java.lang.reflect.Field bgcol = Blob_Labeler.class.getDeclaredField("bgcol");
        bgcol.setAccessible(true);
        java.lang.reflect.Field edge = Blob_Labeler.class.getDeclaredField("edge");
        edge.setAccessible(true);

        // the plugin prints the run time of every run; that is noise here
        java.io.PrintStream original = System.out;
        System.setOut(new java.io.PrintStream(new java.io.ByteArrayOutputStream()));

        try {
            for (int configuration = 0; configuration < NAMES.length; configuration++) {
                neighb8.setBoolean(null, EIGHT[configuration]);
                bgcol.setInt(null, BGCOL[configuration]);
                edge.setBoolean(null, EDGE[configuration]);
                // every configuration sees the same images
                state = SEED;
                long checksum = 0;
                int failedRounds = 0;
                for (int round = 0; round < count; round++) {
                    int width = WIDTHS[round % WIDTHS.length];
                    int height = HEIGHTS[round % HEIGHTS.length];
                    byte[] pixels = randomImage(round, width, height);
                    short[] map = new short[width * height];
                    int labels = 0;
                    int failed = 0;
                    try {
                        Blob_Labeler blob = new Blob_Labeler();
                        blob.run(new ij.process.ByteProcessor(width, height, pixels));
                        ij.ImagePlus result = blob.getResult();
                        if (result != null) {
                            map = (short[]) result.getProcessor().getPixels();
                            labels = labelCount(result.getTitle());
                        }
                    } catch (Throwable failure) {
                        failed = 1;
                        failedRounds++;
                        map = new short[width * height];
                        labels = 0;
                    }
                    checksum = (checksum * 31 + failed) % MOD;
                    checksum = (checksum * 31 + labels + 1) % MOD;
                    for (int i = 0; i < map.length; i++) {
                        checksum = (checksum * 31 + map[i] + 1) % MOD;
                    }
                }
                checksums[configuration] = checksum;
                failures[configuration] = failedRounds;
            }
        } finally {
            System.setOut(original);
        }

        long combined = 0;
        for (int configuration = 0; configuration < NAMES.length; configuration++) {
            System.out.println(String.format("%-14s checksum=%10d failed rounds=%d",
                    NAMES[configuration], checksums[configuration], failures[configuration]));
            combined = (combined * 31 + checksums[configuration]) % MOD;
        }
        System.out.println("combined   : " + combined);
        System.out.println("checked    : " + count + " random image(s) per configuration, "
                + NAMES.length + " configurations");

        if (count != COUNT) {
            System.out.println("the checksums belong to " + COUNT
                    + " images, so they are only reported here");
            System.out.println("ALL-PASS: the original Blob_Labeler answered every image");
            return;
        }
        for (int configuration = 0; configuration < NAMES.length; configuration++) {
            if (checksums[configuration] != EXPECTED_CHECKSUMS[configuration]) {
                System.out.println("FAIL: the checksum of " + NAMES[configuration] + " is "
                        + checksums[configuration] + ", the original is expected to compute "
                        + EXPECTED_CHECKSUMS[configuration]);
                System.exit(1);
            }
            if (failures[configuration] != EXPECTED_FAILURES[configuration]) {
                System.out.println("FAIL: " + NAMES[configuration] + " fails on "
                        + failures[configuration] + " image(s), the original is expected to fail on "
                        + EXPECTED_FAILURES[configuration]);
                System.exit(1);
            }
        }
        if (combined != EXPECTED_COMBINED) {
            System.out.println("FAIL: the combined checksum is " + combined
                    + ", the original is expected to compute " + EXPECTED_COMBINED);
            System.exit(1);
        }
        System.out.println("ALL-PASS: all six configurations of the original Blob_Labeler"
                + " match the pinned checksums");
    }

    /** The fold of the six checksums. */
    public static final long EXPECTED_COMBINED = 482399897L;

    /** The random image of a round (the generator is shared with the port). */
    private static byte[] randomImage(int round, int width, int height) {
        byte[] pixels = new byte[width * height];
        // three families of densities: half of the pixels are foreground, two
        // thirds and four fifths
        int range = 2 + (round % 3);
        for (int i = 0; i < pixels.length; i++) {
            pixels[i] = (byte) (next() % range);
        }
        return pixels;
    }

    /** Blob_Labeler names its result image "blobs 4c <n>" / "blobs 8c <n>". */
    private static int labelCount(String title) {
        int index = title.lastIndexOf(' ');
        return Integer.parseInt(title.substring(index + 1).trim());
    }
}
