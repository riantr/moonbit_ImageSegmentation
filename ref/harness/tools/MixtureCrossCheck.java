/**
 * A differential cross check of the original `MixtureModeling_` against the
 * MoonBit port.
 *
 * The mixture model is the last of the histogram algorithms of the suite: it
 * fits two Gaussian components to the histogram and reports the mean, the
 * variance, the fitting error and two thresholds of the fit. Its output is
 * floating point, and the corpus already compares it **bit for bit** - but
 * only on the images of the corpus.
 *
 * The interesting inputs are the degenerate histograms: a single bin (one
 * component has no pixels at all), two levels, an empty one, a histogram with
 * everything in the last bin. On those the fit degenerates — the component
 * without pixels gets the variance zero, and its density function then
 * returns zero for every grey level instead of dividing by zero. The result
 * stays finite (the plugin never produces a NaN or an infinity), but the
 * means, the variances, the error and the thresholds are completely
 * different from the ones of a balanced histogram.
 *
 * So both implementations are driven with the **same** random images and the
 * results are pinned to **shared checksums**:
 *
 *   * this tool fails when the **Java** original computes something else,
 *   * the MoonBit test fails when the **port** computes something else,
 *
 * so a divergence shows up on the side that caused it. The images are
 * generated by a linear congruential generator, so no file has to be
 * exchanged.
 *
 * The floating point values are folded into the checksum through their **raw
 * IEEE-754 bit patterns** - a decimal comparison with a tolerance would hide a
 * difference in the last bit. The bit patterns are folded as **unsigned**
 * 32 bit values, so the checksum stays positive on both sides.
 *
 * Usage:
 *     javac -encoding UTF-8 -cp out -d tools\out tools\MixtureCrossCheck.java
 *     java -cp "out;tools\out" MixtureCrossCheck [count]
 *
 * With a different number of images the checksum is only reported (the
 * constant belongs to the default number of images).
 */
public class MixtureCrossCheck {
    /** The number of random images. */
    public static final int COUNT = 64;

    /** The seed of the linear congruential generator. */
    public static final int SEED = 20261101;

    /** The modulus of the checksum. */
    private static final long MOD = 1000000007L;

    /** The checksum of the thresholds and the statistics. */
    public static final long EXPECTED_CHECKSUM = 166889024L;

    /**
     * The number of images on which the plugin raises.
     *
     * It must be zero: the plugin answers every image, and a round that
     * raised would silently drop out of the checksum. The count is therefore
     * pinned, exactly like the failing rounds of the blob labeler.
     */
    public static final int EXPECTED_FAILURES = 0;

    /** The widths of the images. */
    public static final int[] WIDTHS = { 24, 16, 32, 8, 12, 7, 20, 16 };

    /** The heights of the images. */
    public static final int[] HEIGHTS = { 20, 16, 24, 8, 10, 5, 32, 4 };

    /** The state of the generator. */
    private static int state = SEED;

    /** The next value of the generator (the same arithmetic as in Java). */
    private static int next() {
        state = (1103515245 * state + 12345) & 0x7FFFFFFF;
        return state;
    }

    public static void main(String[] args) {
        int count = args.length > 0 ? Integer.parseInt(args[0]) : COUNT;
        long checksum = 0;
        int failed = 0;

        // the plugin prints into the console; that is noise here
        java.io.PrintStream original = System.out;
        System.setOut(new java.io.PrintStream(new java.io.ByteArrayOutputStream()));

        try {
            for (int round = 0; round < count; round++) {
                int width = WIDTHS[round % WIDTHS.length];
                int height = HEIGHTS[round % HEIGHTS.length];
                byte[] pixels = randomImage(round, width, height);
                ij.IJ.MESSAGES.clear();
                ij.ImagePlus.CREATED.clear();
                MixtureModeling_ mixture = new MixtureModeling_();
                try {
                    mixture.run(new ij.process.ByteProcessor(width, height, pixels));
                } catch (Throwable e) {
                    failed++;
                    continue;
                }
                checksum = (checksum * 31 + bits(mu1()) + 1) % MOD;
                checksum = (checksum * 31 + bits(variance1()) + 1) % MOD;
                checksum = (checksum * 31 + bits(mu2()) + 1) % MOD;
                checksum = (checksum * 31 + bits(variance2()) + 1) % MOD;
                checksum = (checksum * 31 + bits(errorMin()) + 1) % MOD;
                checksum = (checksum * 31 + bits(diffMu()) + 1) % MOD;
                checksum = (checksum * 31 + directThreshold() + 1) % MOD;
                checksum = (checksum * 31 + bits(realThreshold()) + 1) % MOD;
                byte[] binary = binaryImage();
                for (int i = 0; i < binary.length; i++) {
                    checksum = (checksum * 31 + (binary[i] & 0xff) + 1) % MOD;
                }
            }
        } finally {
            System.setOut(original);
        }

        System.out.println("checksum   : " + checksum);
        System.out.println("checked    : " + count + " random image(s), " + failed + " failed");

        if (count != COUNT) {
            System.out.println("the checksum belongs to " + COUNT
                    + " images, so it is only reported here");
            System.out.println("ALL-PASS: the original MixtureModeling_ answered every image");
            return;
        }
        if (failed != EXPECTED_FAILURES) {
            System.out.println("FAIL: the plugin raised on " + failed
                    + " image(s), it is expected to raise on " + EXPECTED_FAILURES);
            System.exit(1);
        }
        if (checksum != EXPECTED_CHECKSUM) {
            System.out.println("FAIL: the checksum is " + checksum
                    + ", the original MixtureModeling_ is expected to compute "
                    + EXPECTED_CHECKSUM);
            System.exit(1);
        }
        System.out.println("ALL-PASS: the original MixtureModeling_ matches the pinned checksum");
    }

    /** The raw bit pattern of a float, as an unsigned 32 bit value. */
    private static long bits(float value) {
        return Float.floatToRawIntBits(value) & 0xFFFFFFFFL;
    }

    /** The float of the message that starts with the given prefix. */
    private static float floatMessage(String prefix) {
        return Float.parseFloat(after(prefix).trim());
    }

    /** The integer of the message that starts with the given prefix. */
    private static int intMessage(String prefix) {
        return Integer.parseInt(after(prefix).trim());
    }

    /** The first message that starts with the given prefix. */
    private static String message(String prefix) {
        for (String message : ij.IJ.MESSAGES) {
            if (message.startsWith(prefix)) {
                return message;
            }
        }
        throw new IllegalStateException("no IJ message starting with '" + prefix
                + "' in " + ij.IJ.MESSAGES);
    }

    /** The text behind the first message that starts with the given prefix. */
    private static String after(String prefix) {
        return message(prefix).substring(prefix.length());
    }

    /** The text between two markers of the message that starts with the prefix. */
    private static String between(String prefix, String start, String end) {
        String message = message(prefix);
        int from = message.indexOf(start);
        if (from < 0) {
            throw new IllegalStateException("no '" + start + "' in '" + message + "'");
        }
        int to = message.indexOf(end, from + start.length());
        if (to < 0) {
            throw new IllegalStateException("no '" + end + "' in '" + message + "'");
        }
        return message.substring(from + start.length(), to).trim();
    }

    /** The text behind the marker of the message that starts with the prefix. */
    private static String tail(String prefix, String marker) {
        String message = after(prefix);
        int index = message.indexOf(marker);
        if (index < 0) {
            throw new IllegalStateException("no '" + marker + "' in '" + message + "'");
        }
        return message.substring(index + marker.length()).trim();
    }

    private static float mu1() {
        return Float.parseFloat(between("Mu1 : ", "Mu1 : ", ", variance1 : "));
    }

    private static float variance1() {
        return Float.parseFloat(tail("Mu1 : ", ", variance1 : "));
    }

    private static float mu2() {
        return Float.parseFloat(between("Mu2 : ", "Mu2 : ", ", variance2 : "));
    }

    private static float variance2() {
        return Float.parseFloat(tail("Mu2 : ", ", variance2 : "));
    }

    private static float errorMin() {
        return floatMessage("ErrorMin : ");
    }

    private static float diffMu() {
        return floatMessage("Diff Mu : ");
    }

    private static int directThreshold() {
        return intMessage("Direct threshold : ");
    }

    private static float realThreshold() {
        return floatMessage("Real threshold : ");
    }

    /** The binary image the plugin produces. */
    private static byte[] binaryImage() {
        if (ij.ImagePlus.CREATED.isEmpty()) {
            throw new IllegalStateException("the plugin produced no image");
        }
        ij.ImagePlus image = ij.ImagePlus.CREATED.get(ij.ImagePlus.CREATED.size() - 1);
        return (byte[]) image.getProcessor().getPixels();
    }

    /**
     * The random image of a round (the generator is shared with the port).
     *
     * The generator is advanced once per pixel in every shape, so the two
     * sides consume the same numbers even in the shapes that do not use them.
     */
    private static byte[] randomImage(int round, int width, int height) {
        int size = width * height;
        byte[] pixels = new byte[size];
        int shape = round % 8;
        for (int i = 0; i < size; i++) {
            state = next();
            int value;
            switch (shape) {
                case 0: {
                    // sixteen grey levels
                    value = state % 16;
                    break;
                }
                case 1: {
                    // two levels
                    value = (state % 2 == 0) ? 0 : 255;
                    break;
                }
                case 2: {
                    // a ramp
                    value = i % 256;
                    break;
                }
                case 3: {
                    // a single grey level
                    value = state % 256;
                    break;
                }
                case 4: {
                    // sparse noise on a background
                    value = (state % 10 == 0) ? (state % 256) : 0;
                    break;
                }
                case 5: {
                    // completely black
                    value = 0;
                    break;
                }
                case 6: {
                    // a gradient
                    value = (i * 255) / Math.max(1, size - 1);
                    break;
                }
                default: {
                    // two halves with two levels
                    value = (i < size / 2) ? 40 : 200;
                    break;
                }
            }
            pixels[i] = (byte) value;
        }
        return pixels;
    }
}
