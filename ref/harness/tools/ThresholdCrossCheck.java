/**
 * A differential cross check of the original `OtsuThresholding_` and of the
 * original `Multi_OtsuThreshold` against the MoonBit port.
 *
 * The QA report listed the image corpus as the only coverage of the two
 * threshold plugins. A corpus is a set of pictures - it contains no histogram
 * on purpose, and a histogram is exactly what these two plugins consume. The
 * interesting cases are the ones a picture does not produce: a histogram with
 * a single bin, a histogram with everything in the last bin, a histogram with
 * two levels, an empty one, and the levels 2, 3 and 5 of the multi level
 * search (the plugin hard codes 4, but its `findMaxSigma` implements all of
 * them and so does the port).
 *
 * So both implementations are driven with the **same** random images and the
 * results are pinned to **shared checksums**:
 *
 *   * this tool fails when the **Java** original computes something else,
 *   * the MoonBit test fails when the **port** computes something else,
 *
 * so a divergence shows up on the side that caused it. The images are
 * generated by a linear congruential generator, so no file has to be
 * exchanged.
 *
 * The four configurations:
 *
 *   * `otsu` - the `OtsuThresholding_` plugin: the threshold it reports and
 *     the binary image it produces,
 *   * `multiotsu2` … `multiotsu4` - the `Multi_OtsuThreshold` plugin with the
 *     level counts 2, 3 and 4: the thresholds it finds.
 *
 * The level count 5 is deliberately **not** fuzzed: its search is four nested
 * loops over the 256 grey levels, about 160 million iterations per histogram,
 * which would make the unit test minutes long on the slower backends. The
 * corpus of the suite compares it on every one of its 25 images instead.
 *
 * The multi level search is driven through the same code path as the plugin
 * uses: `buildHistogram` -> `buildLookupTables` -> `findMaxSigma`.
 *
 * Usage:
 *     javac -encoding UTF-8 -cp out -d tools\out tools\ThresholdCrossCheck.java
 *     java -cp "out;tools\out" ThresholdCrossCheck [count]
 *
 * With a different number of images the checksums are only reported (the
 * constants belong to the default number of images).
 */
public class ThresholdCrossCheck {
    /** The number of random images. */
    public static final int COUNT = 64;

    /** The seed of the linear congruential generator. */
    public static final int SEED = 20261030;

    /** The modulus of the checksum. */
    private static final long MOD = 1000000007L;

    /** The names of the five configurations. */
    public static final String[] NAMES = {
        "otsu", "multiotsu2", "multiotsu3", "multiotsu4"
    };

    /**
     * The number of images of every configuration.
     *
     * The search of the multi level Otsu is a nested loop over the 256 grey
     * levels: one loop for the level count 2, two for 3, three for 4 and four
     * for 5. The level count 5 is therefore about 160 million iterations per
     * histogram and is **not** fuzzed here - the corpus of the suite compares
     * it on every one of its 25 images instead. The counts of the fuzzed
     * levels are scaled by their cost, so that the test stays quick.
     */
    public static final int[] COUNTS = { 64, 32, 16, 8 };

    /** The level count of every configuration (0 is the single level Otsu). */
    public static final int[] MLEVELS = { 0, 2, 3, 4 };

    /** The checksum of every configuration, in the order of {@link #NAMES}. */
    public static final long[] EXPECTED_CHECKSUMS = {
        600913906L, 828034254L, 59404614L, 289251653L
    };

    /** The fold of the four checksums. */
    public static final long EXPECTED_COMBINED = 697755534L;

    /** The widths of the images. */
    public static final int[] WIDTHS = { 24, 16, 32, 8, 12, 7, 20, 16 };

    /** The heights of the images. */
    public static final int[] HEIGHTS = { 20, 16, 24, 8, 10, 5, 32, 4 };

    /** The state of the generator. */
    private static int state = SEED;

    /** The next value of the generator (the same arithmetic as in Java). */
    private static int next() {
        state = (1103515245 * state + 12345) & 0x7FFFFFFF;
        return state;
    }

    public static void main(String[] args) {
        int[] counts = COUNTS.clone();
        for (int i = 0; i < counts.length && i < args.length; i++) {
            counts[i] = Integer.parseInt(args[i]);
        }
        boolean standard = true;
        for (int i = 0; i < counts.length; i++) {
            if (counts[i] != COUNTS[i]) {
                standard = false;
            }
        }
        long[] checksums = new long[NAMES.length];
        long combined = 0;

        // the plugins print into the console; that is noise here
        java.io.PrintStream original = System.out;
        System.setOut(new java.io.PrintStream(new java.io.ByteArrayOutputStream()));

        try {
            for (int configuration = 0; configuration < NAMES.length; configuration++) {
                // every configuration sees the same images
                state = SEED;
                long checksum = 0;
                int count = counts[configuration];
                for (int round = 0; round < count; round++) {
                    int width = WIDTHS[round % WIDTHS.length];
                    int height = HEIGHTS[round % HEIGHTS.length];
                    byte[] pixels = randomImage(round, width, height);
                    int mlevel = MLEVELS[configuration];
                    if (mlevel == 0) {
                        checksum = (checksum * 31 + otsuThreshold(width, height, pixels) + 1) % MOD;
                        byte[] binary = otsuImage();
                        for (int i = 0; i < binary.length; i++) {
                            checksum = (checksum * 31 + (binary[i] & 0xff) + 1) % MOD;
                        }
                    } else {
                        Multi_OtsuThreshold multiOtsu = new Multi_OtsuThreshold();
                        float[] h = new float[256];
                        multiOtsu.buildHistogram(h, pixels.clone(), width, height);
                        float[][] p = new float[256][256];
                        float[][] s = new float[256][256];
                        float[][] hh = new float[256][256];
                        multiOtsu.buildLookupTables(p, s, hh, h);
                        int[] thresholds = new int[mlevel];
                        multiOtsu.findMaxSigma(mlevel, hh, thresholds);
                        for (int k = 0; k < mlevel; k++) {
                            checksum = (checksum * 31 + thresholds[k] + 1) % MOD;
                        }
                    }
                }
                checksums[configuration] = checksum;
            }
        } finally {
            System.setOut(original);
        }

        for (int configuration = 0; configuration < NAMES.length; configuration++) {
            System.out.println(String.format("%-12s checksum=%10d images=%d",
                    NAMES[configuration], checksums[configuration], counts[configuration]));
            combined = (combined * 31 + checksums[configuration]) % MOD;
        }
        System.out.println("combined   : " + combined);
        System.out.println("checked    : " + NAMES.length + " configurations");

        if (!standard) {
            System.out.println("the checksums belong to the default number of images ("
                    + "64/32/16/8), so they are only reported here");
            System.out.println("ALL-PASS: the original plugins answered every image");
            return;
        }
        for (int configuration = 0; configuration < NAMES.length; configuration++) {
            if (checksums[configuration] != EXPECTED_CHECKSUMS[configuration]) {
                System.out.println("FAIL: the checksum of " + NAMES[configuration] + " is "
                        + checksums[configuration] + ", the original is expected to compute "
                        + EXPECTED_CHECKSUMS[configuration]);
                System.exit(1);
            }
        }
        if (combined != EXPECTED_COMBINED) {
            System.out.println("FAIL: the combined checksum is " + combined
                    + ", the original is expected to compute " + EXPECTED_COMBINED);
            System.exit(1);
        }
        System.out.println("ALL-PASS: the original OtsuThresholding_ and Multi_OtsuThreshold"
                + " match the pinned checksums");
    }

    /** The threshold the Otsu plugin reports. */
    private static int otsuThreshold(int width, int height, byte[] pixels) {
        ij.IJ.MESSAGES.clear();
        ij.ImagePlus.CREATED.clear();
        OtsuThresholding_ otsu = new OtsuThresholding_();
        otsu.run(new ij.process.ByteProcessor(width, height, pixels));
        for (String message : ij.IJ.MESSAGES) {
            if (message.startsWith("Found threshold : ")) {
                return Integer.parseInt(message.substring("Found threshold : ".length()).trim());
            }
        }
        throw new IllegalStateException("no threshold in " + ij.IJ.MESSAGES);
    }

    /** The binary image the Otsu plugin produces. */
    private static byte[] otsuImage() {
        if (ij.ImagePlus.CREATED.isEmpty()) {
            throw new IllegalStateException("the Otsu plugin produced no image");
        }
        ij.ImagePlus image = ij.ImagePlus.CREATED.get(ij.ImagePlus.CREATED.size() - 1);
        return (byte[]) image.getProcessor().getPixels();
    }

    /**
     * The random image of a round (the generator is shared with the port).
     *
     * The generator is advanced once per pixel in every shape, so the two
     * sides consume the same numbers even in the shapes that do not use them.
     */
    private static byte[] randomImage(int round, int width, int height) {
        int size = width * height;
        byte[] pixels = new byte[size];
        int shape = round % 8;
        for (int i = 0; i < size; i++) {
            state = next();
            int value;
            switch (shape) {
                case 0: {
                    // sixteen grey levels
                    value = state % 16;
                    break;
                }
                case 1: {
                    // two levels
                    value = (state % 2 == 0) ? 0 : 255;
                    break;
                }
                case 2: {
                    // a ramp
                    value = i % 256;
                    break;
                }
                case 3: {
                    // a single grey level
                    value = state % 256;
                    break;
                }
                case 4: {
                    // sparse noise on a background
                    value = (state % 10 == 0) ? (state % 256) : 0;
                    break;
                }
                case 5: {
                    // completely black
                    value = 0;
                    break;
                }
                case 6: {
                    // a gradient
                    value = (i * 255) / Math.max(1, size - 1);
                    break;
                }
                default: {
                    // two halves with two levels
                    value = (i < size / 2) ? 40 : 200;
                    break;
                }
            }
            pixels[i] = (byte) value;
        }
        return pixels;
    }
}
