/**
 * A differential cross check of the original `SioxSegmentator` against the
 * MoonBit port.
 *
 * SIOX is the only algorithm of the suite whose **colour conversion** runs on
 * a platform dependent power: the sRGB gamma (the exponent 2.4) and the
 * CIELAB cube root (the exponent 1/3) of the colour conversion of SIOX.
 *
 * The first audit measured that these two exponents differ by one unit in the
 * last place of the double on about 0.1 % of the arguments (QA_REPORT.md
 * §5.2). The difference is narrowed to a float right afterwards, which
 * absorbs it — unless it lands exactly on a float rounding boundary, or
 * unless it **flips a cluster boundary**: the Lab coordinates decide the
 * clusters, and a coordinate that differs in the last bit can put a pixel in
 * another cluster. The corpus of the suite (25 images) never showed such a
 * case; this gate looks for it with random colours.
 *
 * Both implementations are driven with the **same** random images and the
 * results are pinned to **shared checksums**:
 *
 *   * this tool fails when the **Java** original computes something else,
 *   * the MoonBit test fails when the **port** computes something else,
 *
 * so a divergence shows up on the side that caused it. The images are
 * generated by a linear congruential generator, so no file has to be
 * exchanged.
 *
 * The confidence matrix is compared through its **raw IEEE-754 bit
 * patterns** - a decimal comparison with a tolerance would hide exactly the
 * difference this gate is looking for.
 *
 * The failure paths are part of the comparison: the original raises an
 * `IllegalStateException` when the foreground signature does not exist and
 * returns `false` when the background signature is empty. The number of
 * failing images is pinned as well.
 *
 * Usage:
 *     javac -encoding UTF-8 -cp out -d tools\out tools\SioxCrossCheck.java
 *     java -cp "out;tools\out" SioxCrossCheck [count]
 *
 * With a different number of images the checksum is only reported (the
 * constant belongs to the default number of images).
 */
public class SioxCrossCheck {
    /** The number of random images. */
    public static final int COUNT = 64;

    /** The seed of the linear congruential generator. */
    public static final int SEED = 20261102;

    /** The modulus of the checksum. */
    private static final long MOD = 1000000007L;

    /** The checksum of the confidence matrices. */
    public static final long EXPECTED_CHECKSUM = 15384133L;

    /**
     * The number of images on which the original raises.
     *
     * It is not zero: the completely black shape has no foreground signature,
     * and the original raises an `IllegalStateException` on it. The count is
     * pinned, exactly like the failing rounds of the blob labeler.
     */
    public static final int EXPECTED_FAILURES = 8;

    /** The widths of the images. */
    public static final int[] WIDTHS = { 16, 20, 12, 24, 8, 32, 16, 28 };

    /** The heights of the images. */
    public static final int[] HEIGHTS = { 12, 16, 12, 20, 8, 24, 16, 14 };

    /** The state of the generator. */
    private static int state = SEED;

    /** The next value of the generator (the same arithmetic as in Java). */
    private static int next() {
        state = (1103515245 * state + 12345) & 0x7FFFFFFF;
        return state;
    }

    public static void main(String[] args) {
        int count = args.length > 0 ? Integer.parseInt(args[0]) : COUNT;
        long checksum = 0;
        int failed = 0;
        int[] successCount = new int[2];

        // the plugins print into the console; that is noise here
        java.io.PrintStream original = System.out;
        System.setOut(new java.io.PrintStream(new java.io.ByteArrayOutputStream()));

        try {
            for (int round = 0; round < count; round++) {
                int width = WIDTHS[round % WIDTHS.length];
                int height = HEIGHTS[round % HEIGHTS.length];
                int[] argb = new int[width * height];
                float[] cm = new float[width * height];
                for (int i = 0; i < argb.length; i++) {
                    int[] rgba = pixel(round, width, height, i);
                    argb[i] = 0xFF000000 | (rgba[0] << 16) | (rgba[1] << 8) | rgba[2];
                    // the confidence of the known strokes, exactly as the
                    // reference harness builds it from the grey level
                    int grey = rgba[3];
                    cm[i] = (grey <= 63) ? 0.0f : ((grey >= 192) ? 1.0f : 0.5f);
                }
                int success = 0;
                int failure = 0;
                try {
                    siox.SioxSegmentator siox = new siox.SioxSegmentator(width, height,
                            new float[]{0.64f, 1.28f, 2.56f});
                    success = siox.segmentate(argb, cm, 1, 4.0) ? 1 : 0;
                } catch (Throwable e) {
                    // the original raises when the foreground signature does
                    // not exist; the confidence matrix keeps its partial state
                    failure = 1;
                    failed++;
                }
                successCount[success]++;
                checksum = (checksum * 31 + failure) % MOD;
                checksum = (checksum * 31 + success) % MOD;
                for (int i = 0; i < cm.length; i++) {
                    checksum = (checksum * 31 + bits(cm[i]) + 1) % MOD;
                }
            }
        } finally {
            System.setOut(original);
        }

        System.out.println("checksum   : " + checksum);
        System.out.println("checked    : " + count + " random image(s), " + failed + " failed");
        System.out.println("succeeded  : " + successCount[1] + ", returned false: "
                + successCount[0]);

        if (count != COUNT) {
            System.out.println("the checksum belongs to " + COUNT
                    + " images, so it is only reported here");
            System.out.println("ALL-PASS: the original SioxSegmentator answered every image");
            return;
        }
        if (failed != EXPECTED_FAILURES) {
            System.out.println("FAIL: the original raised on " + failed
                    + " image(s), it is expected to raise on " + EXPECTED_FAILURES);
            System.exit(1);
        }
        if (checksum != EXPECTED_CHECKSUM) {
            System.out.println("FAIL: the checksum is " + checksum
                    + ", the original SioxSegmentator is expected to compute "
                    + EXPECTED_CHECKSUM);
            System.exit(1);
        }
        System.out.println("ALL-PASS: the original SioxSegmentator matches the pinned checksum");
    }

    /** The raw bit pattern of a float, as an unsigned 32 bit value. */
    private static long bits(float value) {
        return Float.floatToRawIntBits(value) & 0xFFFFFFFFL;
    }

    /**
     * The pixel of an image: the red, the green and the blue channel and the
     * grey level that decides its confidence.
     *
     * The generator is advanced **four** times per pixel in every shape, so
     * that the two sides consume the same numbers even in the shapes that do
     * not use them.
     */
    private static int[] pixel(int round, int width, int height, int index) {
        int a = next();
        int b = next();
        int c = next();
        int d = next();
        int shape = round % 8;
        int size = width * height;
        int x = index % width;
        int grey;
        int r;
        int g;
        int bl;
        switch (shape) {
            case 0: {
                // a dark and a bright half, greyish colours
                grey = (x < width / 2) ? 20 : 220;
                r = clamp(grey + (a % 21) - 10);
                g = clamp(grey + (b % 21) - 10);
                bl = clamp(grey + (c % 21) - 10);
                break;
            }
            case 1: {
                // a dark and an unknown half, greyish colours
                grey = (x < width / 2) ? 20 : 128;
                r = clamp(grey + (a % 21) - 10);
                g = clamp(grey + (b % 21) - 10);
                bl = clamp(grey + (c % 21) - 10);
                break;
            }
            case 2: {
                // completely random colours
                grey = a % 256;
                r = b % 256;
                g = c % 256;
                bl = d % 256;
                break;
            }
            case 3: {
                // a gradient with the colours of the reference harness
                grey = (index * 255) / Math.max(1, size - 1);
                r = grey;
                g = (grey * 3) / 4;
                bl = 255 - grey;
                break;
            }
            case 4: {
                // completely black: no foreground signature at all
                grey = 0;
                r = 0;
                g = 0;
                bl = 0;
                break;
            }
            case 5: {
                // completely white: no background signature at all
                grey = 255;
                r = 255;
                g = 255;
                bl = 255;
                break;
            }
            case 6: {
                // a dark and a bright half with completely random colours -
                // the colour conversion is what decides the clusters here
                grey = (x < width / 2) ? 20 : 220;
                r = b % 256;
                g = c % 256;
                bl = d % 256;
                break;
            }
            default: {
                // a random grey level with one dominant channel
                grey = a % 256;
                r = b % 256;
                // the sum of two generator values overflows the 32 bit, so the
                // low byte is taken with a mask - the same arithmetic as in
                // MoonBit, where the `Int` wraps like a Java `int`
                g = (b + c) & 0xFF;
                bl = d % 256;
                break;
            }
        }
        return new int[]{ r, g, bl, grey };
    }

    /** The value clamped into `0..255`. */
    private static int clamp(int value) {
        if (value < 0) {
            return 0;
        }
        if (value > 255) {
            return 255;
        }
        return value;
    }
}
