/**
 * A differential cross check of the **fifteen** threshold methods of the
 * original `AutoThresholder` against the MoonBit port.
 *
 * The QA report listed as a residual risk that "the `Li` cross check covers one
 * method of the fifteen" — the other fourteen were only covered by the image
 * corpus, not by a fuzz. This tool closes that gap.
 *
 * The mechanism is the one of `LiCrossCheck.java`: both implementations are
 * driven with exactly the same hostile histograms and the results are pinned to
 * **shared checksums**. The checksum of every method is the same constant in
 * this file and in the MoonBit test
 * `the fifteen threshold methods match the original AutoThresholder on hostile
 * histograms` (`segmentation_test.mbt`):
 *
 *   * this tool fails when the **Java** original computes something else,
 *   * the MoonBit test fails when the **port** computes something else,
 *
 * so a divergence shows up on the side that caused it.
 *
 * The histograms are the shapes that make the iteration interesting:
 *
 *   * a single non zero bin (the mean is the bin, the background and the
 *     object mean are 0),
 *   * the two extreme bins (the logarithmic mean of 0 and 255),
 *   * everything in the last bin, everything in the first bin,
 *   * a completely empty histogram (the mean is NaN),
 *   * sparse and dense random histograms,
 *   * a single spike.
 *
 * They are generated by a linear congruential generator, so both
 * implementations see exactly the same ones without any file to exchange. The
 * generator is **restarted for every method**, so every method sees the same
 * sequence of histograms and the checksum of a method depends on that method
 * alone.
 *
 * Every method of the original was measured first: none of them raises an
 * exception on any of the shapes (24000 calls, zero exceptions), so a method
 * that throws here is a defect of the original and not of the port.
 *
 * Usage:
 *     javac -encoding UTF-8 -cp out -d tools\out tools\AutoThresholderCrossCheck.java
 *     java -cp "out;tools\out" AutoThresholderCrossCheck [rounds]
 *
 * With a different number of rounds the checksums are only reported (the
 * constants belong to the default number of rounds); the run still fails when a
 * method raises.
 */
public class AutoThresholderCrossCheck {
    /** The number of histograms per method. */
    public static final int COUNT = 64;

    /** The seed of the linear congruential generator. */
    public static final int SEED = 20261030;

    /** The names of the fifteen methods, in the order of the Java table. */
    public static final String[] METHOD_NAMES = {
        "Huang", "Intermodes", "IsoData", "Li", "MaxEntropy", "Mean",
        "MinError(I)", "Minimum", "Moments", "Otsu", "Percentile",
        "RenyiEntropy", "Shanbhag", "Triangle", "Yen"
    };

    /** The checksum of every method, in the order of {@link #METHOD_NAMES}. */
    public static final long[] EXPECTED_CHECKSUMS = {
        107048180L, 880944531L, 273794009L, 431563462L, 686060938L,
        956456453L, 517811581L, 924797356L, 662340405L, 901090455L,
        934842986L, 670314028L, 879143749L, 799090228L, 299050832L
    };

    /** The fold of the fifteen checksums. */
    public static final long EXPECTED_COMBINED = 981417562L;

    /** The state of the generator. */
    private static int state = SEED;

    /** The next value of the generator (the same arithmetic as in Java). */
    private static int next() {
        state = (1103515245 * state + 12345) & 0x7FFFFFFF;
        return state;
    }

    public static void main(String[] args) {
        int rounds = args.length > 0 ? Integer.parseInt(args[0]) : COUNT;
        String[] methods = AutoThresholder.getMethods();
        if (methods.length != METHOD_NAMES.length) {
            System.out.println("FAIL: the original has " + methods.length
                    + " methods, the port has " + METHOD_NAMES.length);
            System.exit(1);
        }
        for (int i = 0; i < methods.length; i++) {
            if (!methods[i].equals(METHOD_NAMES[i])) {
                System.out.println("FAIL: the method " + i + " is '" + methods[i]
                        + "', the port calls it '" + METHOD_NAMES[i] + "'");
                System.exit(1);
            }
        }

        AutoThresholder thresholder = new AutoThresholder();
        long combined = 0;
        boolean failed = false;

        for (int i = 0; i < methods.length; i++) {
            String method = methods[i];
            // every method sees the same sequence of histograms
            state = SEED;
            long checksum = 0;
            int min = Integer.MAX_VALUE;
            int max = Integer.MIN_VALUE;
            for (int round = 0; round < rounds; round++) {
                int[] histogram = hostileHistogram(round);
                int threshold;
                try {
                    threshold = thresholder.getThreshold(method, histogram);
                } catch (Throwable e) {
                    System.out.println("FAIL: " + method + " raised on histogram " + round
                            + ": " + e);
                    System.exit(1);
                    return;
                }
                if (threshold < min) {
                    min = threshold;
                }
                if (threshold > max) {
                    max = threshold;
                }
                checksum = (checksum * 31 + (threshold + 1)) % 1000000007L;
            }
            combined = (combined * 31 + checksum) % 1000000007L;
            System.out.println(String.format("%-14s checksum=%10d range=%d..%d",
                    method, checksum, min, max));
            if (rounds == COUNT && checksum != EXPECTED_CHECKSUMS[i]) {
                System.out.println("FAIL: the checksum of " + method + " is " + checksum
                        + ", the original is expected to compute " + EXPECTED_CHECKSUMS[i]);
                failed = true;
            }
        }

        System.out.println("combined   : " + combined);
        System.out.println("checked    : " + rounds + " hostile histograms per method, "
                + methods.length + " methods");

        if (rounds != COUNT) {
            System.out.println("the checksums belong to " + COUNT
                    + " rounds, so they are only reported here");
            System.out.println("ALL-PASS: the original AutoThresholder raises on no histogram");
            return;
        }
        if (failed) {
            System.exit(1);
        }
        if (combined != EXPECTED_COMBINED) {
            System.out.println("FAIL: the combined checksum is " + combined
                    + ", the original is expected to compute " + EXPECTED_COMBINED);
            System.exit(1);
        }
        System.out.println("ALL-PASS: all fifteen methods of the original AutoThresholder"
                + " match the pinned checksums");
    }

    /** The hostile histogram of a round (the generator is shared with the port). */
    private static int[] hostileHistogram(int round) {
        int[] histogram = new int[256];
        switch (round % 8) {
            case 0: {
                // a single bin
                int bin = next() % 256;
                histogram[bin] = 1 + next() % 1000;
                break;
            }
            case 1: {
                // the two extreme bins
                histogram[0] = next() % 100;
                histogram[255] = next() % 100;
                break;
            }
            case 2: {
                // everything in the last bin
                histogram[255] = 1 + next() % 1000;
                break;
            }
            case 3: {
                // everything in the first bin
                histogram[0] = 1 + next() % 1000;
                break;
            }
            case 4: {
                // a completely empty histogram (the mean is NaN)
                break;
            }
            case 5: {
                // a sparse random histogram
                for (int i = 0; i < 256; i++) {
                    histogram[i] = next() % 3;
                }
                break;
            }
            case 6: {
                // a dense random histogram
                for (int i = 0; i < 256; i++) {
                    histogram[i] = next() % 1000;
                }
                break;
            }
            default: {
                // a single spike
                histogram[next() % 256] = 1 + next() % 100;
                break;
            }
        }
        return histogram;
    }
}
