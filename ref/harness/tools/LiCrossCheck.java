/**
 * A differential cross check of the `Li` method of the original
 * `AutoThresholder` against the MoonBit port.
 *
 * The QA report listed as a residual risk that the `Li` method "can index
 * outside the 256 bin histogram" (Java raises an
 * `ArrayIndexOutOfBoundsException`, the port panics). That claim turned out
 * to be **false**: the iteration variable of `Li` is the logarithmic mean of
 * two means that both live in `0..255`, so the threshold can never exceed
 * 255 and the read `data[0..threshold]` always stays inside the array.
 *
 * Instead of arguing about it, both implementations are driven with the very
 * same hostile histograms and the results are pinned to a **shared checksum**.
 * The checksum is the same constant in this file and in the MoonBit test
 * `the Li threshold matches the original AutoThresholder on hostile
 * histograms` (`segmentation_test.mbt`):
 *
 *   * this tool fails when the **Java** original computes something else,
 *   * the MoonBit test fails when the **port** computes something else,
 *
 * so a divergence on any of the histograms shows up on the side that caused
 * it. The histograms are the shapes that make the iteration interesting:
 *
 *   * a single non zero bin (the mean is the bin, the background and the
 *     object mean are 0),
 *   * the two extreme bins (the logarithmic mean of 0 and 255),
 *   * everything in the last bin, everything in the first bin,
 *   * a completely empty histogram (the mean is NaN),
 *   * sparse and dense random histograms.
 *
 * The histograms are generated by a linear congruential generator, so both
 * implementations see exactly the same ones without any file to exchange.
 *
 * Usage:
 *     javac -encoding UTF-8 -cp out -d tools\out tools\LiCrossCheck.java
 *     java -cp "out;tools\out" LiCrossCheck [rounds]
 *
 * With a different number of rounds the checksum is only reported (the
 * constant belongs to the default number of rounds); the run still fails when
 * a read leaves the histogram.
 */
public class LiCrossCheck {
    /** The checksum of the thresholds of the hostile histograms. */
    public static final long EXPECTED_CHECKSUM = 333878761L;

    /** The number of hostile histograms. */
    public static final int COUNT = 1000;

    /** The seed of the linear congruential generator. */
    public static final int SEED = 20261030;

    /** The state of the generator. */
    private static int state = SEED;

    /** The next value of the generator (the same arithmetic as in Java). */
    private static int next() {
        state = (1103515245 * state + 12345) & 0x7FFFFFFF;
        return state;
    }

    public static void main(String[] args) {
        int rounds = args.length > 0 ? Integer.parseInt(args[0]) : COUNT;
        long checksum = 0;
        int min = Integer.MAX_VALUE;
        int max = Integer.MIN_VALUE;
        AutoThresholder thresholder = new AutoThresholder();

        for (int round = 0; round < rounds; round++) {
            int[] histogram = hostileHistogram(round);
            int threshold;
            try {
                threshold = thresholder.Li(histogram);
            } catch (ArrayIndexOutOfBoundsException e) {
                System.out.println("round " + round + ": the histogram was left: " + e);
                System.exit(1);
                return;
            }
            if (threshold < min) {
                min = threshold;
            }
            if (threshold > max) {
                max = threshold;
            }
            checksum = (checksum * 31 + (threshold + 1)) % 1000000007L;
        }

        System.out.println("checked       : " + rounds + " hostile histograms");
        System.out.println("threshold range: " + min + " .. " + max);
        System.out.println("checksum      : " + checksum);

        if (rounds != COUNT) {
            System.out.println("the checksum belongs to " + COUNT
                    + " rounds, so it is only reported here");
            System.out.println("ALL-PASS: the original AutoThresholder never leaves the histogram");
            return;
        }
        if (checksum != EXPECTED_CHECKSUM) {
            System.out.println("FAIL: the checksum is " + checksum
                    + ", the original AutoThresholder is expected to compute " + EXPECTED_CHECKSUM);
            System.exit(1);
        }
        System.out.println("ALL-PASS: the original AutoThresholder never leaves the histogram");
    }

    /** The hostile histogram of a round (the generator is shared with the port). */
    private static int[] hostileHistogram(int round) {
        int[] histogram = new int[256];
        switch (round % 8) {
            case 0: {
                // a single bin
                int bin = next() % 256;
                histogram[bin] = 1 + next() % 1000;
                break;
            }
            case 1: {
                // the two extreme bins
                histogram[0] = next() % 100;
                histogram[255] = next() % 100;
                break;
            }
            case 2: {
                // everything in the last bin
                histogram[255] = 1 + next() % 1000;
                break;
            }
            case 3: {
                // everything in the first bin
                histogram[0] = 1 + next() % 1000;
                break;
            }
            case 4: {
                // a completely empty histogram (the mean is NaN)
                break;
            }
            case 5: {
                // a sparse random histogram
                for (int i = 0; i < 256; i++) {
                    histogram[i] = next() % 3;
                }
                break;
            }
            case 6: {
                // a dense random histogram
                for (int i = 0; i < 256; i++) {
                    histogram[i] = next() % 1000;
                }
                break;
            }
            default: {
                // a single spike
                histogram[next() % 256] = 1 + next() % 100;
                break;
            }
        }
        return histogram;
    }
}
